"""RA-003: renderer determinism, drift, ownership, and loading.

The instruction-loading fixture at the bottom is the PRD §5 requirement:
a harness that actually reads the generated file must find the commands,
policy version, and notes — a file's presence alone is insufficient.
"""
import json
from pathlib import Path

from repo_agent import cli, render

CONFIG = """
schema_version: 1
project:
  name: fixture-repo
  maturity: new
commands:
  lint: [ruff, check, .]
  test: [pytest, -q]
  verify: [lint, test]
instructions:
  policy_version: '1.0.0'
skills:
  required: [code-quality-guard]
execution:
  max_attempts: 4
"""

NOTES = "Fixture notes: the cache invalidates on config change.\n"


def make_repo(tmp_path: Path) -> Path:
    (tmp_path / "repo-agent.yaml").write_text(CONFIG, encoding="utf-8")
    (tmp_path / "AGENTS.project.md").write_text(NOTES, encoding="utf-8")
    return tmp_path


def test_write_is_byte_stable_across_repos(tmp_path):
    a, b = tmp_path / "a", tmp_path / "b"
    a.mkdir()
    b.mkdir()
    make_repo(a)
    make_repo(b)
    assert cli.main(["render", str(a), "--write"]) == 0
    assert cli.main(["render", str(b), "--write"]) == 0
    assert (a / "AGENTS.md").read_bytes() == (b / "AGENTS.md").read_bytes()


def test_generated_content_has_no_timestamp_and_records_digests(tmp_path):
    repo = make_repo(tmp_path)
    assert cli.main(["render", str(repo), "--write"]) == 0
    text = (repo / "AGENTS.md").read_text(encoding="utf-8")
    assert "2026" not in text and "generated by: repo-agent" in text
    assert "config sha256:" in text
    assert "policy version: 1.0.0" in text


def test_check_detects_drift_without_writing(tmp_path):
    repo = make_repo(tmp_path)
    code = cli.main(["render", str(repo), "--check"])
    assert code == 1
    assert not (repo / "AGENTS.md").exists()
    assert cli.main(["render", str(repo), "--write"]) == 0
    assert cli.main(["render", str(repo), "--check"]) == 0


def test_drift_follows_input_changes(tmp_path):
    repo = make_repo(tmp_path)
    assert cli.main(["render", str(repo), "--write"]) == 0
    (repo / "AGENTS.project.md").write_text(NOTES + "Amended.\n", encoding="utf-8")
    assert cli.main(["render", str(repo), "--check"]) == 1


def test_write_never_touches_project_notes(tmp_path):
    repo = make_repo(tmp_path)
    before = (repo / "AGENTS.project.md").read_bytes()
    assert cli.main(["render", str(repo), "--write"]) == 0
    assert (repo / "AGENTS.project.md").read_bytes() == before


def test_refuses_unowned_agents_md(tmp_path):
    repo = make_repo(tmp_path)
    (repo / "AGENTS.md").write_text(
        "# Hand-written instructions\nKeep off the mainframe.\n", encoding="utf-8"
    )
    code = cli.main(["render", str(repo), "--write"])
    assert code == 3
    assert (repo / "AGENTS.md").read_text(encoding="utf-8").startswith(
        "# Hand-written instructions"
    )
    payload = json.loads(json.dumps({}))  # placeholder no-op for json import symmetry
    assert payload == {}


def test_refuses_unowned_agents_md_json_reason(tmp_path, capsys):
    repo = make_repo(tmp_path)
    (repo / "AGENTS.md").write_text("# hand\n", encoding="utf-8")
    cli.main(["render", str(repo), "--write"])
    payload = json.loads(capsys.readouterr().out)
    assert payload["reason_code"] == "unowned_agents_md"


def test_missing_config_is_usage_error(tmp_path, capsys):
    assert cli.main(["render", str(tmp_path), "--write"]) == 2
    payload = json.loads(capsys.readouterr().out)
    assert payload["reason_code"] == "config_missing"


def test_invalid_config_surfaces_reason_code(tmp_path, capsys):
    repo = make_repo(tmp_path)
    (repo / "repo-agent.yaml").write_text(
        CONFIG + "\nsurprise: 1\n", encoding="utf-8"
    )
    assert cli.main(["render", str(repo), "--write"]) == 2
    payload = json.loads(capsys.readouterr().out)
    assert payload["reason_code"] == "unknown_field"


def test_instruction_loading_fixture(tmp_path):
    """A harness that reads the generated file finds what it needs."""
    repo = make_repo(tmp_path)
    (repo / "scoped").mkdir()
    (repo / "scoped" / "web-notes.md").write_text("web scope\n", encoding="utf-8")
    config = CONFIG.replace(
        "instructions:\n  policy_version: '1.0.0'\n",
        "instructions:\n  policy_version: '1.0.0'\n"
        "  scoped: [scoped/web-notes.md]\n",
    )
    (repo / "repo-agent.yaml").write_text(config, encoding="utf-8")
    assert cli.main(["render", str(repo), "--write"]) == 0

    loaded = (repo / "AGENTS.md").read_text(encoding="utf-8")

    def fake_harness(text: str) -> dict[str, str]:
        found = {"commands": [], "notes": "", "policy": "", "scoped": []}
        for line in text.splitlines():
            if line.startswith("- lint: `"):
                found["commands"].append(line)
            if line.startswith("- test: `"):
                found["commands"].append(line)
            if line.startswith("- policy version: "):
                found["policy"] = line.split(": ", 1)[1]
            if "Fixture notes:" in line:
                found["notes"] = line
            if "scoped/web-notes.md" in line:
                found["scoped"].append(line)
        return found  # type: ignore[return-value]

    seen = fake_harness(loaded)
    assert len(seen["commands"]) == 2
    assert seen["policy"] == "1.0.0"
    assert "cache invalidates on config change" in seen["notes"]
    assert seen["scoped"], "scoped file referenced with digest"
    assert "web scope" not in loaded, "scoped content must not be flattened"
    # scoped list is ordered regardless of YAML order: digest pins content
    assert render.GENERATED_END in loaded
