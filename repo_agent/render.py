"""RA-003: deterministic instruction rendering.

AGENTS.md is a pure projection of the validated config and the project
notes: identical inputs produce identical bytes in any checkout, with no
timestamps. Rendering never modifies the notes, never runs the commands it
lists, and never overwrites an AGENTS.md that repo-agent does not own.
"""
import hashlib
from pathlib import Path

from repo_agent import __version__
from repo_agent.config import LoadedConfig, ValidationError, load

CONFIG_NAME = "repo-agent.yaml"
AGENTS_NAME = "AGENTS.md"
DEFAULT_NOTES = "AGENTS.project.md"
GENERATED_BEGIN = (
    "<!-- repo-agent:generated — do not edit by hand; regenerate with "
    "`repo-agent render --write` -->"
)
GENERATED_END = "<!-- /repo-agent:generated -->"

_EXIT_OK = 0
_EXIT_DRIFT = 1
_EXIT_USAGE = 2
_EXIT_BLOCKED = 3

_COMMAND_ORDER = ("lint", "test", "verify")


def _digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _commands_section(commands: dict[str, object]) -> list[str]:
    lines: list[str] = ["## Commands", ""]
    names = [n for n in _COMMAND_ORDER if n in commands]
    names += sorted(n for n in commands if n not in _COMMAND_ORDER)
    for name in names:
        value = commands[name]
        assert isinstance(value, list)
        argv = " ".join(value)
        if name == "verify":
            lines.append(f"- verify: runs `{argv}` in order")
        else:
            lines.append(f"- {name}: `{argv}`")
    lines.append("")
    lines.append(
        "These commands are declared in repo-agent.yaml; whether they "
        "currently pass is a question for `repo-agent doctor` and the "
        "verifier, not an assumption."
    )
    lines.append("")
    return lines


def render_bytes(
    loaded: LoadedConfig, repo_root: Path, notes_path: str, notes_text: str
) -> bytes:
    cfg = loaded.config
    project = cfg.get("project", {})
    assert isinstance(project, dict)
    instructions = cfg.get("instructions", {})
    assert isinstance(instructions, dict)
    execution = cfg.get("execution", {})
    assert isinstance(execution, dict)
    skills = cfg.get("skills", {})
    assert isinstance(skills, dict)
    boundaries = cfg.get("boundaries", {})
    assert isinstance(boundaries, dict)
    policy_version = instructions.get("policy_version", "unspecified")

    out: list[str] = [
        GENERATED_BEGIN,
        "",
        f"# {project.get('name', 'project')} — agent instructions",
        "",
        f"- generated by: repo-agent {__version__} (deterministic projection)",
        f"- policy version: {policy_version}",
        f"- config sha256: {loaded.source['sha256']}",
        f"- notes: {notes_path} (sha256 {_digest(notes_text.encode('utf-8'))[:16]})",
        "",
        "## Working rules",
        "",
        "- Read before editing: inspect the surrounding code and these",
        "  instructions before changing anything.",
        "- Preserve user changes and the declared boundaries; never commit",
        "  unrelated work.",
        "- Reuse before writing: existing helpers, then stdlib, then",
        "  installed dependencies, then new code.",
        "- Handle failures at their cause; malformed input is routine.",
        "- Verify with the declared commands and report honestly: state",
        "  what ran, what failed, and what was skipped.",
        f"- Bounded retries: at most {execution.get('max_attempts', 3)} "
        "attempts; two failures without new evidence escalate instead of "
        "retrying.",
        "",
    ]

    out += ["## Project", "", f"- maturity: {project.get('maturity', 'unspecified')}"]
    if "architecture" in project:
        out.append(f"- architecture: {project['architecture']}")
    out.append("")

    commands = cfg.get("commands", {})
    assert isinstance(commands, dict)
    out += _commands_section(commands)

    if any(boundaries.get(k) for k in ("generated", "sensitive", "preserve")):
        out += ["## Boundaries", ""]
        generated = boundaries.get("generated")
        sensitive = boundaries.get("sensitive")
        preserve = boundaries.get("preserve")
        if generated:
            joined = ", ".join(generated)
            out.append(f"- generated (do not hand-edit): {joined}")
        if sensitive:
            joined = ", ".join(sensitive)
            out.append(f"- sensitive (extra care, no surprises): {joined}")
        if preserve:
            joined = ", ".join(preserve)
            out.append(f"- preserved: {joined}")
        out.append("")

    required = skills.get("required", [])
    conditional = skills.get("conditional", [])
    if required or conditional:
        out += ["## Skills", ""]
        if required:
            joined = ", ".join(required)
            out.append(f"- required: {joined}")
        if conditional:
            joined = ", ".join(conditional)
            out.append(f"- conditional: {joined}")
        lock = skills.get("lock_file")
        if lock:
            out.append(f"- pinned in: {lock}")
        out.append("")

    scoped = instructions.get("scoped", [])
    if scoped:
        out += ["## Scoped instructions", ""]
        out.append(
            "Loaded per scope, not flattened here; digests pin what was "
            "rendered against:"
        )
        out.append("")
        for rel in scoped:
            assert isinstance(rel, str)
            scoped_file = repo_root / rel
            scoped_bytes = scoped_file.read_bytes() if scoped_file.is_file() else b""
            out.append(f"- {rel} (sha256 {_digest(scoped_bytes)[:16]})")
        out.append("")

    if notes_text.strip():
        out += [
            "## Project notes (verbatim from " + notes_path + ")",
            "",
            notes_text.rstrip(),
            "",
        ]

    out += [GENERATED_END, ""]
    return "\n".join(out).encode("utf-8")


def _notes_target(loaded: LoadedConfig) -> str:
    instructions = loaded.config.get("instructions", {})
    assert isinstance(instructions, dict)
    notes = instructions.get("project_notes", DEFAULT_NOTES)
    assert isinstance(notes, str)
    return notes


def _is_owned(existing: bytes) -> bool:
    return GENERATED_BEGIN.encode("utf-8") in existing


def render_repo(repo_root: Path, write: bool) -> tuple[int, dict[str, object]]:
    config_path = repo_root / CONFIG_NAME
    if not config_path.is_file():
        return _EXIT_USAGE, {
            "ok": False,
            "reason_code": "config_missing",
            "detail": f"{CONFIG_NAME} not found in {repo_root}",
        }
    try:
        loaded = load(config_path, repo_root=repo_root)
    except ValidationError as exc:
        return _EXIT_USAGE, {"ok": False, "reason_code": exc.reason_code, "detail": str(exc)}

    notes_rel = _notes_target(loaded)
    notes_file = repo_root / notes_rel
    notes_text = notes_file.read_text(encoding="utf-8") if notes_file.is_file() else ""
    generated = render_bytes(loaded, repo_root, notes_rel, notes_text)

    agents_path = repo_root / AGENTS_NAME
    if agents_path.is_file() and not _is_owned(agents_path.read_bytes()):
        return _EXIT_BLOCKED, {
            "ok": False,
            "reason_code": "unowned_agents_md",
            "detail": "existing AGENTS.md has no repo-agent ownership marker; "
            "migrate it with `repo-agent bootstrap --mode mature --apply` first",
        }

    if not write:
        drift = (not agents_path.is_file()) or agents_path.read_bytes() != generated
        payload: dict[str, object] = {
            "ok": not drift,
            "reason_code": "drift" if drift else "ok",
            "drift": drift,
        }
        if drift:
            return _EXIT_DRIFT, payload
        return _EXIT_OK, payload

    tmp = agents_path.with_suffix(".md.repo-agent-tmp")
    tmp.write_bytes(generated)
    tmp.replace(agents_path)
    return _EXIT_OK, {"ok": True, "reason_code": "ok", "written": AGENTS_NAME}
